"""Refresh literal certificate data from exact.json; this is not a verifier.

Lean checks the resulting integer identities and their real-probability bridge.
The script never changes the proof section of ScheduleCertificate.lean.
"""
import argparse
import json
from fractions import Fraction
from math import comb
from pathlib import Path

root = Path(__file__).resolve().parent.parent
data = json.loads((root / 'certificates/exact.json').read_text())
assert data['denominator'] == 64
assert data['schedules'] == [f'{a:06b}' for a in range(64)]
assert all(len(row) == 64 for row in data['witness_numerators'])

def vector(xs):
    return '![' + ', '.join(map(str, xs)) + ']'

rows = ',\n  '.join(vector(xs) for xs in data['witness_numerators'])

def integer(q):
    q = Fraction(q)
    assert q.denominator == 1
    return q.numerator

targets = [[integer(64 * Fraction(q)) for q in row]
           for row in data['window_target']]
prefix_dual = [[0] * 7 for _ in range(7)]
source_dual = iter(data['prefix_dual'])
prefix_dual[0][0] = integer(next(source_dual))
for j in range(1, 7):
    for k in range(j):
        prefix_dual[j][k] = integer(next(source_dual))
assert next(source_dual, None) is None
window_dual = [[data['direction'][2*w], 0, 0, data['direction'][2*w+1]]
               for w in range(3)]

def matrix(xs):
    return '![' + ',\n    '.join(vector(row) for row in xs) + ']'

block = f'''-- BEGIN EXACT DATA (generated by scripts/generate_certificate.py)
def witnessNumerator : Fin 3 → Schedule → ℕ :=
  ![{rows}]

def targetNumerator : Fin 3 → Fin 4 → ℕ :=
  {matrix(targets)}

def uniformWindowNumerator : Fin 4 → ℕ := {vector([8*comb(3,k) for k in range(4)])}

def prefixDual : Fin 7 → Fin 7 → ℤ :=
  {matrix(prefix_dual)}

def windowDual : Fin 3 → Fin 4 → ℤ :=
  {matrix(window_dual)}
-- END EXACT DATA'''
path = root / 'formal/VixOverlap/ScheduleCertificate.lean'
source = path.read_text()
begin = source.index('-- BEGIN EXACT DATA')
end = source.index('-- END EXACT DATA') + len('-- END EXACT DATA')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='check literal data without writing')
args = parser.parse_args()
generated = source[:begin] + block + source[end:]
if args.check:
    if generated != source:
        raise SystemExit('Exact JSON and Lean literal certificate data differ.')
    print('Exact JSON matches Lean literal certificate data.')
else:
    path.write_text(generated)

#!/usr/bin/env python3
"""Transcribe the pinned conditional deck and full states for Lean's kernel.

The existing empty-root generator is deliberately unchanged. Its parser,
card formatter and balanced-tree formatter are reused, but no empty-root
obligation is emitted for this nonempty conditional interface.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import cards2lean

FORMAL = Path(__file__).resolve().parents[1]
BOARD = FORMAL.parent / "board_size"
PINS = {
    "maker/browser_twentythird_maker02.cards.txt":
        "20f7ddbc3acd8c26ab19bbe086f77c31953a182d9f2182e15812a1e2f8584487",
    "verification/browser_twentythird_maker02_cards.json":
        "f3fd3fdc5a19c56c376a4527cbc43ed98e7793869df467afcda838fe40ad99cb",
    "maker/fourteenth-n-repair-prefix.json":
        "a3714d593e7a0328e8a205d402aa8c329c0562b95256beb384dcae8092560466",
}


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def points(rows):
    result = [tuple(row) for row in rows]
    if len(set(result)) != len(result):
        raise ValueError("duplicate state coordinate")
    return result


def point_list(rows):
    return "[" + ", ".join(cards2lean.pt(point) for point in rows) + "]"


def cell_list(rows):
    return "[" + ", ".join(str(14 * (y - 1) + x - 1) for x, y in rows) + "]"


def sources():
    for name, expected in PINS.items():
        if sha((BOARD / name).read_bytes()) != expected:
            raise ValueError("changed accepted input: " + name)
    deck = BOARD / "maker/browser_twentythird_maker02.cards.txt"
    header, cards = cards2lean.parse(deck)
    report = json.loads((BOARD / "verification/browser_twentythird_maker02_cards.json").read_text())
    if header != (15, 15, 25, (0, 0, 0)) or len(cards) != 26:
        raise ValueError("unexpected conditional deck header")
    root = cards[25]
    if (root["h"], root["p"], len(root["A"]), len(root["S"])) != (8, (11, 6), 8, 24):
        raise ValueError("unexpected conditional root")
    parents = report["partitions"]
    states = {}
    for name, count, covered in (("N30", 30, 119), ("N31", 31, 117)):
        parent = parents[name]["parent"]
        maker, breaker = points(parent["maker"]), points(parent["breaker"])
        if (parent["board"] != [1, 1, 14, 14] or parent["turn"] != "Maker"
                or len(maker) != count or len(breaker) != count
                or set(maker) & set(breaker)
                or parents[name]["covered_count"] != covered
                or parents[name]["unresolved_count"] != 16):
            raise ValueError("unexpected full physical state: " + name)
        states[name] = maker, breaker
    if (set(states["N31"][0]) != set(states["N30"][0]) | {(4, 10)}
            or set(states["N31"][1]) != set(states["N30"][1]) | {(4, 11)}):
        raise ValueError("N31 does not preserve every N30 stone")
    prefix = json.loads((BOARD / "maker/fourteenth-n-repair-prefix.json").read_text())
    if (set(points(prefix["parent"]["maker"])) != set(states["N30"][0])
            or set(points(prefix["parent"]["breaker"])) != set(states["N30"][1])):
        raise ValueError("full N30 differs from accepted prefix")
    exceptions = points(report["unresolved_initial_reply_cells"])
    if (set(exceptions) != set(root["S"]) - set(root["A"])
            or report["initial_move"] != [12, 6]):
        raise ValueError("initial reply interface changed")

    header_comment = (
        "-- Generated by tools/maker_closeout_data.py from pinned accepted inputs.\n"
        "-- The kernel checks the emitted propositions; Python is not trusted.\n"
    )
    card_text = "\n".join(f"def c{i} : Card := {cards2lean.card(card)}"
                          for i, card in enumerate(cards))
    tree = cards2lean.balanced([(i, i + 1, None) for i in range(26)],
                              lambda item: f"(.leaf {item[0]} c{item[0]})")
    data = header_comment + f"""import Snaky.Cards

namespace Snaky.GenMakerCloseout

{card_text}

def tree : CTree := {tree}
def getK : Nat → Option Card := tree.get

end Snaky.GenMakerCloseout
"""
    state = header_comment + f"""import Snaky.CardsSound

namespace Snaky.MakerCloseout

/-- Stored coordinates are one-based; the actual board is 14 by 14. -/
def frame : Xf := Xf.ofIndex 0 (-1) (-1)
def cell (p : Pt) : Nat := idx 14 (frame.app p)
def initialClaim : Nat := cell (12, 6)

def n30MakerCoords : List Pt := {point_list(states['N30'][0])}
def n30BreakerCoords : List Pt := {point_list(states['N30'][1])}
def n31MakerCoords : List Pt := {point_list(states['N31'][0])}
def n31BreakerCoords : List Pt := {point_list(states['N31'][1])}
def exceptionCoords : List Pt := {point_list(exceptions)}

def n30Maker : List Nat := {cell_list(states['N30'][0])}
def n30Breaker : List Nat := {cell_list(states['N30'][1])}
def n31Maker : List Nat := {cell_list(states['N31'][0])}
def n31Breaker : List Nat := {cell_list(states['N31'][1])}
def exceptions : List Nat := {cell_list(exceptions)}

theorem n30_coordinate_encoding :
    n30Maker = n30MakerCoords.map cell ∧ n30Breaker = n30BreakerCoords.map cell := ⟨rfl, rfl⟩
theorem n31_coordinate_encoding :
    n31Maker = n31MakerCoords.map cell ∧ n31Breaker = n31BreakerCoords.map cell := ⟨rfl, rfl⟩
theorem exception_coordinate_encoding : exceptions = exceptionCoords.map cell := rfl

/-- Exactly the legal physical Breaker replies after the initial claim. -/
def legalReplies (M W : List Nat) : List Nat :=
  (List.range 196).filter fun b => !((initialClaim :: M).contains b) && !(W.contains b)
def coveredReplies (M W : List Nat) : List Nat :=
  (legalReplies M W).filter fun b => !(exceptions.contains b)
def remainingReplies (M W : List Nat) : List Nat :=
  (legalReplies M W).filter fun b => exceptions.contains b

end Snaky.MakerCloseout
"""
    checks = {}
    for index in range(26):
        checks[f"Snaky/GenMakerCloseout/Card{index:02}.lean"] = header_comment + f"""import Snaky.GenMakerCloseout.Data
import Snaky.CardsSound

namespace Snaky.GenMakerCloseout

set_option maxHeartbeats 0 in
theorem t{index}_ok : (CTree.leaf {index} c{index}).all (cardOK getK) = true := by
  decide +kernel

end Snaky.GenMakerCloseout
"""
    imports = "".join(f"import Snaky.GenMakerCloseout.Card{i:02}\n" for i in range(26))
    check = header_comment + imports + f"""import Snaky.CardsSound

namespace Snaky.GenMakerCloseout

/-- Every one of the 26 ordinary cards passes the unchanged checker. -/
theorem tree_ok : tree.all (cardOK getK) = true := {cards2lean.glue_proof(0, 26)}

end Snaky.GenMakerCloseout
"""
    count_checks = {}
    rows = [[14 * y + x for x in range(14)] for y in range(14)]
    row_defs = "\n".join(f"def boardRow{y} : List Nat := {row}" for y, row in enumerate(rows))
    row_sum = " ++ ".join(f"boardRow{y}" for y in range(14))
    count_checks["Snaky/MakerCloseoutCountRows.lean"] = header_comment + f"""import Snaky.MakerCloseoutState

namespace Snaky.MakerCloseout

set_option maxRecDepth 4096
{row_defs}

theorem board_rows : List.range 196 = {row_sum} := rfl

theorem length_board_rows (f : List Nat → List Nat)
    (hf : ∀ a b, f (a ++ b) = f a ++ f b)
    {' '.join(f'{{n{y} : Nat}}' for y in range(14))}
    {' '.join(f'(h{y} : (f boardRow{y}).length = n{y})' for y in range(14))} :
    (f (List.range 196)).length = {' + '.join(f'n{y}' for y in range(14))} := by
  rw [board_rows]
  simp only [hf, List.length_append, {', '.join(f'h{y}' for y in range(14))}] <;> omega

end Snaky.MakerCloseout
"""
    for state_name, legal_count, covered_count in (("N30", 135, 119), ("N31", 133, 117)):
        short = state_name.lower()
        owned = {14 * (y - 1) + x - 1 for x, y in states[state_name][0]} | {81}
        blocked = {14 * (y - 1) + x - 1 for x, y in states[state_name][1]}
        excluded = {14 * (y - 1) + x - 1 for x, y in exceptions}
        for kind, function, count in (("Legal", "legalReplies", legal_count),
                                      ("Covered", "coveredReplies", covered_count),
                                      ("Remaining", "remainingReplies", 16)):
            predicate = f"fun b => !((initialClaim :: {short}Maker).contains b) && !({short}Breaker.contains b)"
            suffix = ("" if kind == "Legal" else
                      ".filter (fun b => !(exceptions.contains b))" if kind == "Covered" else
                      ".filter (fun b => exceptions.contains b)")
            row_proofs = []
            for y, row in enumerate(rows):
                allowed = [b for b in row if b not in owned and b not in blocked]
                total = len(allowed if kind == "Legal" else
                            [b for b in allowed if (b in excluded) == (kind == "Remaining")])
                row_proofs.append(f"private theorem count{y} : (((boardRow{y}.filter ({predicate})){suffix})).length = {total} := rfl")
            unfold_names = "legalReplies" if kind == "Legal" else f"{function} legalReplies"
            family = f"fun row => (row.filter ({predicate})){suffix}"
            count_checks[f"Snaky/MakerCloseoutCount{state_name}{kind}.lean"] = header_comment + f"""import Snaky.MakerCloseoutCountRows

namespace Snaky.MakerCloseout

set_option maxRecDepth 4096
{chr(10).join(row_proofs)}

theorem {short}_{kind.lower()}_count : ({function} {short}Maker {short}Breaker).length = {count} := by
  exact length_board_rows ({family})
    (by intro a b; simp only [List.filter_append]) {' '.join(f'count{y}' for y in range(14))}

end Snaky.MakerCloseout
"""
    return {**checks, **count_checks, "Snaky/GenMakerCloseout/Data.lean": data,
            "Snaky/GenMakerCloseout/Check.lean": check,
            "Snaky/MakerCloseoutState.lean": state}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = sources()
    for relative, text in output.items():
        path = FORMAL / relative
        if args.check:
            if path.read_text() != text:
                raise ValueError("generated Lean source differs: " + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    provenance = dict(status="transcribed_not_kernel_checked", input_sha256=PINS,
        generator_sha256=sha(Path(__file__).read_bytes()),
        reused_formatter_sha256=sha(Path(cards2lean.__file__).read_bytes()),
        generated_sha256={name: sha(text.encode()) for name, text in output.items()},
        no_empty_board_root=True, physical_board=[14, 14], root=25,
        stored_coordinate_translation=[-1, -1])
    if not args.check:
        (FORMAL / "Snaky/GenMakerCloseout/provenance.json").write_text(
            json.dumps(provenance, indent=2, sort_keys=True) + "\n")
    print(json.dumps(provenance, sort_keys=True))


if __name__ == "__main__":
    main()
